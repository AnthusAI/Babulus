import { defineBackend } from "@aws-amplify/backend";
import { auth, applyGoogleEmailVerifiedMapping, dependOnGoogleProvider, restrictToGoogleSignIn } from "./auth/resource.js";
import { applyCognitoDomainPrefix, resolveCognitoDomainPrefix } from "./auth/cognito-domain.js";
import { PROSPECTUS_SIGN_IN_CALLBACK_PATH, addProspectusGoogleOnlyClient } from "./auth/prospectus-google-client.js";
import { resolveAuthRedirectUrls } from "./auth/redirect-urls.js";
import { SealingParameter } from "./session-secret/sealing-parameter.js";
import { sealingParameterName } from "./session-secret/naming.js";
import { data } from "./data/resource.js";
import { storage } from "./storage/resource.js";
import * as dynamodb from 'aws-cdk-lib/aws-dynamodb';

const backend = defineBackend({
  auth,
  data,
  storage,
});

// ==========================================
// Google-only sign-in
// ==========================================
//
// Closes the password path (no self sign-up, no password, SRP or custom flow on the web client, Google as its only
// provider), puts the hosted UI on the `babulus` (production) or `babulus-dev` domain, and adds the Google-only client
// Babulus registers with Prospectus. Every property touched updates in place; nothing here replaces the user pool.
const authRedirectUrls = resolveAuthRedirectUrls();
restrictToGoogleSignIn(
  backend.auth.resources.cfnResources.cfnUserPool,
  backend.auth.resources.cfnResources.cfnUserPoolClient,
);
applyGoogleEmailVerifiedMapping(backend.auth.stack);
// The web client lists Google by name, so it must wait for the provider created in the same update.
dependOnGoogleProvider(backend.auth.stack, backend.auth.resources.cfnResources.cfnUserPoolClient);
applyCognitoDomainPrefix(backend.auth.stack, resolveCognitoDomainPrefix());
const prospectusClient = addProspectusGoogleOnlyClient(backend.auth.stack, backend.auth.resources.userPool, authRedirectUrls);
// The cookie sealing secret is generated by infrastructure (create-only, retained); only its name is published.
const sealingParameter = new SealingParameter(backend.createStack("ProspectusSession"), "SealingParameter", {
  parameterName: sealingParameterName(),
});
backend.addOutput({
  custom: {
    prospectusSignIn: {
      clientId: prospectusClient.ref,
      callbackPath: PROSPECTUS_SIGN_IN_CALLBACK_PATH,
      sessionSecretParameter: sealingParameter.parameterName,
      sessionSecretParameterArn: sealingParameter.parameterArn,
    },
  },
});

// ==========================================
// Rendering is local only
// ==========================================
//
// The Studio backend runs no compute of its own. Video renders run on a
// worker the user starts themselves (`babulus worker`), so there is no ECS
// cluster, task definition, render trigger, worker credential, scheduled
// function or alarm here, and nothing reads the Job table's change stream.
//
// The Job table's stream stays enabled only so this change does not touch the
// table; no consumer reads it, and turning it off is a separate, reviewed step.
const amplifyJobTable = backend.data.resources.cfnResources.amplifyDynamoDbTables['Job'];
if (amplifyJobTable) {
  amplifyJobTable.streamSpecification = {
    streamViewType: dynamodb.StreamViewType.NEW_AND_OLD_IMAGES,
  };
}
