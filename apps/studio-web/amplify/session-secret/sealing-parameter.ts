import { Construct } from "constructs";
import { ArnFormat, CustomResource, Duration, RemovalPolicy, Stack } from "aws-cdk-lib";
import * as iam from "aws-cdk-lib/aws-iam";
import * as lambda from "aws-cdk-lib/aws-lambda";
import * as customResources from "aws-cdk-lib/custom-resources";
import { SEALING_PARAMETER_HANDLER_SOURCE } from "./handler-source.js";

export interface SealingParameterProps {
  /** Absolute SSM parameter name, from `sealingParameterName`. */
  parameterName: string;
  /** Length of the generated value. Default 64. */
  length?: number;
}

/**
 * The cookie sealing secret as a standard SSM SecureString (AWS-managed `aws/ssm` key), generated by infrastructure.
 *
 * CloudFormation cannot create a SecureString, so a small custom resource Lambda puts it. It generates the value at
 * create time and never returns or logs it, so the value is in no template, output or stack event. It is create-only:
 * an update never regenerates it and never overwrites an existing parameter, and delete retains it, so a teardown or a
 * redeploy cannot sign anyone out. Rotate it with `aws ssm put-parameter --overwrite`. Readers get `ssm:GetParameter` on
 * `parameterArn` only.
 */
export class SealingParameter extends Construct {
  public readonly parameterName: string;
  public readonly parameterArn: string;

  constructor(scope: Construct, id: string, props: SealingParameterProps) {
    super(scope, id);
    if (!props.parameterName.startsWith("/")) throw new Error(`SSM parameter name must be absolute: ${props.parameterName}`);
    const length = props.length ?? 64;
    if (!Number.isInteger(length) || length < 32) throw new Error("A generated secret must be at least 32 characters.");
    const stack = Stack.of(this);
    this.parameterName = props.parameterName;
    this.parameterArn = stack.formatArn({
      service: "ssm",
      resource: "parameter",
      resourceName: props.parameterName.slice(1),
      arnFormat: ArnFormat.SLASH_RESOURCE_NAME,
    });

    const role = new iam.Role(this, "Role", {
      assumedBy: new iam.ServicePrincipal("lambda.amazonaws.com"),
      description: "Creates the generated sealing parameter: PutParameter on that one parameter, never overwriting",
      managedPolicies: [iam.ManagedPolicy.fromAwsManagedPolicyName("service-role/AWSLambdaBasicExecutionRole")],
    });
    role.addToPolicy(new iam.PolicyStatement({ sid: "PutSealingParameter", actions: ["ssm:PutParameter"], resources: [this.parameterArn] }));
    const onEvent = new lambda.Function(this, "OnEvent", {
      runtime: lambda.Runtime.NODEJS_22_X,
      handler: "index.handler",
      code: lambda.Code.fromInline(SEALING_PARAMETER_HANDLER_SOURCE),
      role,
      timeout: Duration.seconds(30),
      description: "Creates the generated sealing SecureString once; never returns or logs the value",
    });
    const provider = new customResources.Provider(this, "Provider", { onEventHandler: onEvent });
    const resource = new CustomResource(this, "Resource", {
      serviceToken: provider.serviceToken,
      resourceType: "Custom::SecureStringParameter",
      properties: { ParameterName: props.parameterName, Description: "Seals the Studio's Prospectus sign-in cookies; replacing it signs everyone out", Length: String(length) },
      removalPolicy: RemovalPolicy.RETAIN,
    });
    resource.node.addDependency(role);
  }
}
